-- ================== طلبات: مسعّرة بالكامل من الجدول أعلاه ==================
-- الشكل الجديد: items_data بقت مجرد [{product_id, quantity}, ...]
-- بدون اسم أو سعر جاي من المتصفح؛ الدالة نفسها بتجيب الاسم والسعر من
-- public.products، فمفيش طريقة حد يغيّر سعر صنف من الـ devtools ويأثر على الطلب.
-- رقم الطلب كمان بقى بيتولّد من sequence في قاعدة البيانات فمش ممكن يتكرر.
create sequence if not exists public.order_number_seq;

drop function if exists public.create_order(jsonb, jsonb);

create or replace function public.create_order(order_data jsonb, items_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    new_order_id uuid := gen_random_uuid();
    generated_number text;
    computed_total numeric := 0;
    item jsonb;
    product record;
    quantity integer;
    line_total numeric;
begin
    if items_data is null or jsonb_array_length(items_data) = 0 then
        raise exception 'Order must contain at least one item';
    end if;

    generated_number := 'ORD-' || to_char(now(), 'YYYYMMDD') || '-'
        || lpad(nextval('public.order_number_seq')::text, 4, '0');

    insert into public.orders (
        id, order_number, customer_name, phone, address, notes, payment_method, total, status
    ) values (
        new_order_id,
        generated_number,
        left(trim(order_data->>'customer_name'), 120),
        left(trim(order_data->>'phone'), 40),
        left(trim(order_data->>'address'), 500),
        left(coalesce(order_data->>'notes', ''), 1000),
        case when order_data->>'payment_method' = 'transfer' then 'transfer' else 'cash' end,
        0,
        'new'
    );

    for item in select * from jsonb_array_elements(items_data)
    loop
        select p.* into product
        from public.products p
        where p.id = item->>'product_id' and p.is_active
        limit 1;

        if not found then
            raise exception 'Unknown or unavailable product: %', item->>'product_id';
        end if;

        quantity := least(greatest(coalesce((item->>'quantity')::integer, 1), 1), 20);
        line_total := product.price * quantity;
        computed_total := computed_total + line_total;

        insert into public.order_items (
            order_id, product_id, product_name, size, quantity, unit_price, total_price
        ) values (
            new_order_id,
            product.id,
            product.name,
            coalesce(product.variant_label, ''),
            quantity,
            product.price,
            line_total
        );
    end loop;

    update public.orders set total = computed_total where id = new_order_id;

    return jsonb_build_object('id', new_order_id, 'order_number', generated_number);
end;
$$;

grant execute on function public.create_order(jsonb, jsonb) to anon, authenticated;
