create extension if not exists pgcrypto;

create table if not exists public.orders (
    id uuid primary key default gen_random_uuid(),
    order_number text unique not null,
    customer_name text not null,
    phone text not null,
    address text not null,
    notes text,
    payment_method text not null default 'cash',
    total numeric not null default 0 check (total >= 0),
    status text not null default 'new' check (status in ('new', 'accepted', 'preparing', 'delivering', 'delivered', 'cancelled')),
    created_at timestamptz not null default now()
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id uuid not null references public.orders(id) on delete cascade,
    product_name text not null,
    size text not null,
    quantity integer not null check (quantity between 1 and 20),
    unit_price numeric not null check (unit_price >= 0),
    total_price numeric not null check (total_price >= 0)
);

-- كتالوج المنتجات: المرجع الوحيد للأسعار. الموقع بيعرض القائمة منه مباشرة،
-- ودالة create_order بتسعّر الطلب منه بردو، فمفيش سعر بييجي من المتصفح كما هو.
-- علشان تغيّر سعر أو تضيف أو تشيل صنف بعد كده، عدّل الجدول ده من Table Editor
-- في Supabase (أو شغّل insert/update جديد) وهيتحدث في الموقع والطلبات فورًا.
create table if not exists public.products (
    id text primary key,
    category text not null,
    name text not null,
    variant_label text,
    description text,
    price numeric not null check (price >= 0),
    sort_order integer not null default 0,
    is_active boolean not null default true
);

alter table public.order_items add column if not exists product_id text references public.products(id);

create table if not exists public.admin_users (
    user_id uuid primary key references auth.users(id) on delete cascade
